-- =====================================================================
-- Purpose : County reference data -- FIPS code, state, county name, and
--           one representative ZIP per county. Seeded for Texas only
--           (254 rows); other states are added by later migrations of
--           the same shape.
--
-- Notes   : Not PSP-scoped -- county FIPS codes are national reference
--           data, identical on every installation. Matches the
--           non-scoped precedent of V074 and V075.
--
--           The representative ZIP exists because the HealthSherpa
--           quote API requires zip_code alongside fip_code. Rating does
--           not vary by ZIP within a county (verified: two ZIPs in
--           Hopkins County TX returned identical plan sets across all
--           20 plans), so any in-county ZIP is safe. The representative
--           ZIP is the ZCTA with the greatest share of its land area
--           falling inside the county (containment = the ZCTA's
--           in-county land area / its total land area), tie-broken by
--           lowest numeric ZCTA5 -- not simply the lowest-numbered ZCTA
--           mapped to the county, which can straddle a county line and
--           mostly belong to a neighbor.
--
--           Source: US Census Gazetteer county file (FIPS, name, state)
--           and the Census 2020 ZCTA-to-county relationship file
--           (representative ZIP). Regenerate with
--           docs/scripts/generate_county_reference.ps1.
--
-- Feature : B-2 agent-facing ICHRA illustration. Supersedes the
--           zip:fips:state triple format of RATE_CACHE_COUNTIES (D-83)
--           by moving county identity into the database.
--
-- Prereqs : Base schema (V024 baseline). No prior migration required.
--
-- Scope   : All instances -- reference data, inert where unused.
--
-- Rollback: DROP TABLE county_reference;
-- =====================================================================

CREATE TABLE county_reference (
    county_fips        CHAR(5)      NOT NULL,
    state              CHAR(2)      NOT NULL,
    county_name        VARCHAR(100) NOT NULL,
    representative_zip CHAR(5)      NOT NULL,
    PRIMARY KEY (county_fips),
    KEY idx_county_reference_state_name (state, county_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

